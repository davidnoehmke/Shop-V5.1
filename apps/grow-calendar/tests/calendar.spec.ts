import { test, expect } from '@playwright/test'
test('SSR, filters, empty state and reset work together',async({page,request})=>{
  const response=await request.get('/')
  expect(response.status()).toBe(200)
  expect(await response.text()).toContain('data-crop="tomate"')
  const errors:string[]=[]
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.locator('[data-crop]')).toHaveCount(30)
  await page.getByRole('button',{name:'März',exact:true}).click()
  await page.getByLabel('Kategorie',{exact:true}).selectOption('vegetables')
  await page.getByRole('searchbox').fill('Tomate')
  await expect(page.locator('[data-crop]')).toHaveCount(1)
  await page.getByLabel('Was möchtest du tun?',{exact:true}).selectOption('transplant_outdoors')
  await expect(page.getByText('Ein guter Moment zum Neuplanen.')).toBeVisible()
  await page.getByRole('button',{name:'Filter zurücksetzen'}).click()
  await expect(page.locator('[data-crop]')).toHaveCount(30)
  expect(errors).toEqual([])
})
test('plant details, translation and PDFs retain the selected plant',async({page,request})=>{
  await page.goto('/pflanzen/tomate')
  await expect(page.getByRole('heading',{level:1})).toHaveText('Tomate')
  await page.getByRole('link',{name:'Switch to English'}).click()
  await expect(page.getByRole('heading',{level:1})).toHaveText('Tomato')
  await expect(page.locator('html')).toHaveAttribute('lang','en')
  await expect(page.getByRole('link',{name:'Seed-starting starter set'})).toHaveAttribute('href','https://leaferservice.com/en/products/anzucht-starter-set')
  const pdf=await request.get('/api/crops/tomate/pdf?lang=en')
  expect(pdf.status()).toBe(200)
  expect(pdf.headers()['content-type']).toContain('application/pdf')
  expect((await pdf.body()).subarray(0,5).toString()).toBe('%PDF-')
  expect((await request.get('/pflanzen/not-a-real-crop')).status()).toBe(404)
  expect((await request.get('/api/crops/tomate/pdf?lang=xx')).status()).toBe(400)
})
test('month deep links and canonical URLs are correct',async({page,request})=>{
  await page.goto('/monate/maerz')
  await expect(page.getByRole('heading',{level:1})).toContainText('März')
  await expect(page.getByRole('button',{name:'März',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.locator('link[rel=canonical]')).toHaveAttribute('href','https://leaferservice-grow-calendar.vercel.app/monate/maerz')
  await page.getByRole('link',{name:'Switch to English'}).click()
  await expect(page.getByRole('heading',{level:1})).toContainText('March')
  expect((await request.get('/monate/invalid')).status()).toBe(404)
  await page.goto('/?embedded=1')
  await expect(page.locator('.site-header')).toHaveCount(0)
  await expect(page.locator('meta[name=robots]')).toHaveAttribute('content','noindex,indexifembedded')
})
for(const width of [320,375,430,481,768,1280])test(`no horizontal page overflow at ${width}px`,async({page})=>{
  await page.setViewportSize({width,height:900})
  await page.goto('/')
  await expect(page.locator('[data-crop]')).toHaveCount(30)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true)
  await page.goto('/pflanzen/kapuzinerkresse')
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true)
})
