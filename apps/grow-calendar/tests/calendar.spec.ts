test('Shopify embed resizes, keeps navigation visible and validates messages',async({page,baseURL})=>{
  const host='https://leaferservice.com/__calendar-embed-test__'
  const appOrigin='https://leaferservice-grow-calendar.vercel.app'
  // Keep the real HTTPS origins while serving the isolated application fixture.
  // Public HTTPS pages cannot embed a loopback HTTP origin in current Chromium.
  await page.context().route(`${appOrigin}/**`,async route=>{
    const url=new URL(route.request().url())
    const response=await route.fetch({url:`${baseURL}${url.pathname}${url.search}`})
    await route.fulfill({response})
  })
  const html=readFileSync(new URL('../deployment/shopify-page-de.html',import.meta.url),'utf8')
  await page.route(host,route=>route.fulfill({contentType:'text/html; charset=utf-8',body:`<!doctype html><html lang="de"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>html{scroll-behavior:smooth}body{margin:0}*{box-sizing:border-box}</style></head><body>${html}</body></html>`}))
  await page.setViewportSize({width:375,height:812})
  await page.goto(host)
  const frame=page.frameLocator('#leaf-grow-calendar iframe')
  await expect(page).toHaveTitle('Aussaatkalender: 30 Pflanzen & PDF-Pläne | LEAFerservice')
  await expect(page.locator('meta[name=description]')).toHaveAttribute('content',/30 Pflanzen/)
  await expect(frame.locator('[data-crop]')).toHaveCount(30)
  await expect.poll(async()=>page.locator('iframe').evaluate(el=>Number.parseFloat((el as HTMLIFrameElement).style.height)||0)).toBeGreaterThan(2500)
  const originalHeight=await page.locator('iframe').evaluate(el=>(el as HTMLIFrameElement).style.height)
  await page.evaluate(()=>window.postMessage({type:'leaf-grow-height',height:9999},'*'))
  await expect(page.locator('iframe')).toHaveCSS('height',originalHeight)
  await frame.getByRole('heading',{name:'Tomate',exact:true}).getByRole('link').click()
  await expect(frame.getByRole('heading',{level:1})).toHaveText('Tomate')
  await expect.poll(()=>page.evaluate(()=>window.scrollY)).toBeLessThan(1000)
  await expect(frame.locator('.site-header')).toHaveCount(0)
  // Chromium cannot complete downloads served by route.fulfill (Playwright #28253).
  // Real, unintercepted downloads are exercised in the plant-details test above.
  await expect(frame.getByRole('link',{name:'PDF herunterladen'})).toHaveAttribute('href','/api/crops/tomate/pdf?lang=de')
  await expect(frame.getByRole('link',{name:'PDF herunterladen'})).toHaveAttribute('download','leaferservice-tomate-de.pdf')
  await expect(page.locator('iframe')).toHaveAttribute('sandbox',/allow-downloads/)
  await frame.getByRole('link',{name:'Alle Pflanzen'}).click()
  await expect(frame.locator('[data-crop]')).toHaveCount(30)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1)).toBe(true)
  await page.goto(`${host}#maerz`)
  await page.reload()
  await expect(frame.getByRole('button',{name:'März',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect.poll(()=>page.locator('iframe').evaluate(el=>el.getBoundingClientRect().top)).toBeGreaterThanOrEqual(0)
  await expect.poll(()=>page.locator('iframe').evaluate(el=>el.getBoundingClientRect().top)).toBeLessThan(500)
})
